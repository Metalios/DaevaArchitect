import {pathToFileURL} from 'node:url';
import path from 'node:path';

const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true});
const base=process.env.SHARE_BASE_URL||pathToFileURL(path.resolve('dist/index.html')).href;
const owner=await browser.newPage();
const errors=[];owner.on('pageerror',error=>errors.push(error.message));
await owner.goto(base);
await owner.locator('[data-class="templar"]').click();
await owner.locator('[data-tab="boards"]').click();
await owner.locator('#board-mode-custom').click();
const first=await owner.evaluate(()=>{const board=DATA.templar.boards[0],start=board.nodes.find(n=>n[5]===0);return board.nodes.find(n=>n[5]>0&&Math.abs(n[1]-start[1])+Math.abs(n[2]-start[2])===1)[0]});
await owner.locator(`[data-node="${first}"]`).click();
await owner.locator('[data-tab="gear"]').click();
await owner.locator('#gear-cp-input').fill('38500');await owner.locator('#gear-cp-input').blur();
await owner.locator('#gear-cp-target').fill('75000');await owner.locator('#gear-cp-target').blur();
if(!(await owner.locator('#gear-cp-status').textContent()).includes('51% of target'))throw Error('Combat Power percent missing');
if(!(await owner.locator('#gear-cp-status').textContent()).includes('36,500 CP to go'))throw Error('Combat Power gap missing');
await owner.locator('[data-gear-slot="top"]').click();
await owner.locator('#gear-query').fill('Abyssal');
await owner.locator('[data-gear-result]').first().click();
await owner.locator('.gear-save').click();
await owner.locator('#share-build-button').click();
await owner.waitForFunction(()=>document.querySelector('#share-url').value.includes('#build='));
const link=await owner.locator('#share-url').inputValue();
if(!link.includes('#build='))throw Error('Share URL missing build snapshot');
const recipient=await browser.newPage();recipient.on('pageerror',error=>errors.push(error.message));
await recipient.goto(link);
await recipient.locator('#shared-build-banner').waitFor();
if(!await recipient.locator('#planner-content').isHidden())throw Error('Shared link replaced a fresh save before consent');
await recipient.locator('#shared-build-load').click();
if(await recipient.evaluate(()=>state.class)!=='templar')throw Error('Shared class did not load');
if(await recipient.evaluate(()=>account().boardMode)!=='custom')throw Error('Custom board mode was not shared');
if(await recipient.evaluate(()=>account().customNodes[0])!==first)throw Error('Custom route was not shared');
if(await recipient.evaluate(()=>account().goalObserved)!==38500||await recipient.evaluate(()=>account().goalTarget)!==75000)throw Error('Combat Power comparison was not shared');
await recipient.locator('[data-tab="gear"]').click();
if(!await recipient.locator('[data-gear-slot="top"].filled').count())throw Error('Equipped item was not shared');
if(new URL(recipient.url()).hash)throw Error('Imported build token stayed in the address bar');
await recipient.reload();
if(await recipient.evaluate(()=>account().customNodes[0])!==first)throw Error('Imported route did not persist');
const healer=await browser.newPage();await healer.goto(base);await healer.locator('[data-class="cleric"]').click();await healer.locator('[data-tab="gear"]').click();
await healer.locator('#gear-cp-target').fill('50000');await healer.locator('#gear-cp-target').blur();
await healer.locator('#gear-cp-input').fill('25000');await healer.locator('#gear-cp-input').blur();
if(!(await healer.locator('#gear-cp-status').textContent()).includes('50% of target'))throw Error('Healer optional CP comparison missing');
if(await healer.evaluate(()=>account().goalTarget)!==0)throw Error('Healer CP target changed healing target');
if(errors.length)throw Error(`Browser errors: ${errors.join('; ')}`);
console.log('Shared build import, gear and custom path fidelity, CP target gap, and healer CP tracking passed.');
await browser.close();
