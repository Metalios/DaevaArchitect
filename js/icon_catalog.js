function gameSkillIconFile(cls,name){
  const s=GAME_STIGMA_ART[cls]?.[name];
  if(s)return s[1];
  const skill=Object.values(DATA[cls]?.skills||{}).find(x=>x.name===name);
  const last=skill?.icon?.split('/').pop();
  return /^ICON_[A-Za-z0-9_]+\.(?:webp|png)$/i.test(last||'')?
    last.replace(/\.webp$/i,'.png'):'';
}
function gameSkillIconUrl(cls,name){
  const file=gameSkillIconFile(cls,name);
  return file?GAME_ICON_CDN+file:'';
}
function gameSkillIconMarkup(cls,name,className='game-icon'){
  const url=gameSkillIconUrl(cls,name);
  const safe=String(name).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const label=String(name).split(/\s+/).map(x=>x[0]||'').slice(0,2).join('').toUpperCase()||'✦';
  if(!url)return `<span class="${className} game-icon"><span class="game-icon-fallback">${label}</span></span>`;
  const file=gameSkillIconFile(cls,name).replace(/\.png$/i,'.webp');
  // Fallback to a community skill-icon CDN if NC's public CDN is unavailable.
  const alternate='https://aion2.app/db-item-icons/'+file;
  return `<span class="${className} game-icon" title="${safe}"><span class="game-icon-fallback">${label}</span><img src="${url}" alt="" loading="lazy" decoding="async" data-alternate="${alternate}" onerror="if(!this.dataset.triedAlternate){this.dataset.triedAlternate='1';this.src=this.dataset.alternate}else{this.hidden=true}"></span>`;
}
