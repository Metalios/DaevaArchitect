import {pathToFileURL} from 'node:url';
import path from 'node:path';

const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1360,height:900}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto(process.env.BOARD_BASE_URL||pathToFileURL(path.resolve('dist/index.html')).href);
await page.locator('[data-class="templar"]').click();
await page.locator('[data-tab="boards"]').click();
if(await page.locator('.global-next-step').count())throw Error('Old click list remains above the board');
if(await page.locator('#global-route-next button').count()!==1)throw Error('Expected one next-tile jump');
await page.locator('#global-route-next button').click();
if(await page.locator('#board-grid .node.queued').count()<1)throw Error('Upcoming clicks are not highlighted in the selected board');
if(!await page.locator('#board-grid .node.queued .queue-badge').count())throw Error('Board click order is missing');
if(process.env.BOARD_SCREENSHOT)await page.locator('#boards').screenshot({path:process.env.BOARD_SCREENSHOT});
if(process.env.BOARD_MOBILE_SCREENSHOT){await page.setViewportSize({width:390,height:844});await page.locator('#boards').screenshot({path:process.env.BOARD_MOBILE_SCREENSHOT});await page.setViewportSize({width:1360,height:900})}
await page.locator('#board-grid .node.queued').first().click();
if(!await page.locator('#board-grid .node.obtained').count())throw Error('Recommended tile click did not mark obtained');
await page.locator('[data-board="Nezekan"]').click();
await page.locator('#board-mode-custom').click();
if(await page.locator('#custom-board-tools').isHidden())throw Error('Custom tools are hidden');
if(await page.locator('#global-route-budget').textContent()!=='0 / 136 crystals planned')throw Error('Custom board should start empty');
const adjacent=await page.evaluate(()=>{const board=DATA.templar.boards[0],start=board.nodes.find(n=>n[5]===0);return board.nodes.find(n=>n[5]>0&&Math.abs(n[1]-start[1])+Math.abs(n[2]-start[2])===1)[0]});
const disconnected=await page.evaluate(()=>{const board=DATA.templar.boards[0],start=board.nodes.find(n=>n[5]===0);return board.nodes.find(n=>n[5]>0&&Math.abs(n[1]-start[1])+Math.abs(n[2]-start[2])>1)[0]});
await page.locator(`[data-node="${disconnected}"]`).click();
if(await page.evaluate(()=>account().customNodes.length)!==0)throw Error('Disconnected custom tile was accepted');
await page.locator(`[data-node="${adjacent}"]`).click();
if(!await page.locator(`[data-node="${adjacent}"].planned`).count())throw Error('Connected custom tile was not planned');
if(await page.evaluate(()=>account().customNodes.length)!==1)throw Error('Custom plan was not saved');
await page.locator('#crystal-input').fill('0');await page.locator('#crystal-input').blur();
if(await page.evaluate(()=>model().boards.spent)!==0)throw Error('Custom tile stayed funded after crystal budget fell');
await page.locator('#crystal-input').fill('136');await page.locator('#crystal-input').blur();
if(await page.evaluate(()=>model().boards.spent)!==1)throw Error('Custom tile did not regain funding');
await page.locator('#selected-node-obtained').click();
if(!await page.locator(`[data-node="${adjacent}"].obtained`).count())throw Error('Custom tile was not marked obtained');
await page.locator('#board-mode-recommended').click();
await page.locator('#global-route-next button').click();
if(!await page.locator('#board-grid .node.queued').count())throw Error('Recommended route did not return');
const recommendedEffects=await page.evaluate(()=>JSON.stringify(model().effects));
await page.locator('#board-mode-custom').click();
if(await page.evaluate(()=>account().customNodes.length)!==1)throw Error('Switching modes lost the custom route');
await page.locator('#copy-recommended-board').click();
if(await page.evaluate(()=>account().customNodes.length)<20)throw Error('Copy recommendation did not populate custom route');
if(await page.evaluate(()=>JSON.stringify(model().effects))!==recommendedEffects)throw Error('Copied board effects differ from recommendation');
await page.locator('#clear-custom-board').click();
if(await page.evaluate(()=>account().customNodes.length)!==0)throw Error('Clear custom route failed');
if(errors.length)throw Error(`Browser errors: ${errors.join('; ')}`);
console.log('Recommended board highlights, custom route editing, obtained marks and mode switching passed.');
await browser.close();
